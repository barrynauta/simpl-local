#!/usr/bin/env bash
# The one entry point of the stack (build profile run 14, D131).
#   ./stack.sh up               start (returns when usable; no-op when already running)
#   ./stack.sh down             stop
#   ./stack.sh images           print every image of the stack
#   ./stack.sh store-down-up    start the second backend with an unreachable store (port 8199)
#   ./stack.sh store-down-down  remove it
set -euo pipefail
cd "$(dirname "$0")"
export COMPOSE_PROJECT_NAME=vm-factory-run14

random() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 32; }

ensure_env() {
  if [ ! -f .env ]; then
    umask 077
    cat > .env <<ENV
# Local secrets, generated by stack.sh. Never commit this file (D131).
FUSEKI_READ_USER=vm_read
FUSEKI_READ_PASSWORD=$(random)
FUSEKI_UPDATE_USER=vm_update
FUSEKI_UPDATE_PASSWORD=$(random)
FUSEKI_ADMIN_USER=vm_admin
FUSEKI_ADMIN_PASSWORD=$(random)
KEYCLOAK_ADMIN_USER=kcadmin
KEYCLOAK_ADMIN_PASSWORD=$(random)
ENV
  fi
}

case "${1:-}" in
  up)
    ensure_env
    DOCKER_BUILDKIT=1 docker compose up -d --build --wait --wait-timeout 600
    ;;
  down)
    docker compose --profile storedown down
    ;;
  images)
    ensure_env
    docker compose --profile storedown config --images | sort -u
    ;;
  store-down-up)
    ensure_env
    docker compose --profile storedown up -d --wait --wait-timeout 300 backend-store-down
    ;;
  store-down-down)
    docker compose --profile storedown rm -sf backend-store-down
    ;;
  *)
    echo "usage: $0 up|down|images|store-down-up|store-down-down" >&2
    exit 2
    ;;
esac
