#!/usr/bin/env bash
# Entry point of the orchestrator for the Vocabulary Manager stack (build profile run 8).
#   ./stack.sh up              start the stack (returns when usable; no-op when it already runs)
#   ./stack.sh down            stop the stack
#   ./stack.sh images          print every image of the stack, one per line
#   ./stack.sh store-down-up   start a second backend with an unreachable store on port 8199 (D44)
#   ./stack.sh store-down-down remove that backend
set -euo pipefail
cd "$(dirname "$0")"
PROJECT=vm-factory-run8
COMPOSE=(docker compose -p "$PROJECT" -f compose.yaml)

ensure_env() {
  if [[ ! -f .env ]]; then
    umask 077
    rnd() { LC_ALL=C tr -dc 'A-Za-z0-9' < /dev/urandom | head -c 32; }
    cat > .env <<ENV
# Generated by stack.sh: local secrets of this stack, never committed (OpenBao in production, E6).
STORE_READ_USER=vm-reader
STORE_READ_PASSWORD=$(rnd)
STORE_UPDATE_USER=vm-writer
STORE_UPDATE_PASSWORD=$(rnd)
STORE_BACKUP_USER=vm-backup
STORE_BACKUP_PASSWORD=$(rnd)
KEYCLOAK_ADMIN_USER=kc-admin
KEYCLOAK_ADMIN_PASSWORD=$(rnd)
KEYCLOAK_PUBLIC_URL=http://localhost:8193
UI_PUBLIC_URL=http://localhost:4433
VOCABULARY_CONTENT_BASE_URL=https://authority.example/vocabulary-manager
ENV
  fi
}

case "${1:-}" in
  up)
    ensure_env
    "${COMPOSE[@]}" up -d --build --wait --wait-timeout 600
    ;;
  down)
    ensure_env
    "${COMPOSE[@]}" --profile storedown down --remove-orphans
    ;;
  images)
    ensure_env
    "${COMPOSE[@]}" --profile storedown --profile tools config --images | sort -u
    ;;
  store-down-up)
    ensure_env
    "${COMPOSE[@]}" --profile storedown up -d --wait --wait-timeout 300 backend-store-down
    ;;
  store-down-down)
    ensure_env
    "${COMPOSE[@]}" --profile storedown rm -s -f backend-store-down
    ;;
  *)
    echo "usage: $0 up|down|images|store-down-up|store-down-down" >&2
    exit 2
    ;;
esac
