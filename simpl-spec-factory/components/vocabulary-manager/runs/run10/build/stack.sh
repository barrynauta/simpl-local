#!/usr/bin/env bash
# The one entry point of the stack for the orchestrator.
#   ./stack.sh up               start the stack (returns when usable; does nothing if it already runs)
#   ./stack.sh down             stop and remove the stack (data volume kept; add --volumes to drop it)
#   ./stack.sh images           print every image of the stack, one per line
#   ./stack.sh store-down-up    start a second backend whose store is unreachable, API on port 8199
#   ./stack.sh store-down-down  remove that backend
#   ./stack.sh metrics          print the Prometheus metrics of each backend (management port, D86, D98)
set -euo pipefail

cd "$(dirname "$0")"
PROJECT=vm-factory-run10
COMPOSE=(docker compose -p "${PROJECT}")

ensure_env() {
  if [[ ! -f .env ]]; then
    umask 077
    {
      echo "# Local secrets of the stack, generated by stack.sh (not committed). Production uses OpenBao (E6)."
      echo "STORE_READ_PASSWORD=$(openssl rand -hex 24)"
      echo "STORE_UPDATE_PASSWORD=$(openssl rand -hex 24)"
      echo "STORE_ADMIN_PASSWORD=$(openssl rand -hex 24)"
      echo "KEYCLOAK_ADMIN_PASSWORD=$(openssl rand -hex 24)"
    } > .env
  fi
}

case "${1:-}" in
  up)
    ensure_env
    "${COMPOSE[@]}" up -d --build --wait
    "${COMPOSE[@]}" --profile tools build store-tools >/dev/null
    ;;
  down)
    shift
    "${COMPOSE[@]}" --profile store-down --profile tools down --remove-orphans "$@"
    ;;
  images)
    ensure_env
    "${COMPOSE[@]}" --profile store-down --profile tools config --images | sort -u
    ;;
  store-down-up)
    ensure_env
    "${COMPOSE[@]}" --profile store-down up -d --no-deps --wait backend-store-down
    ;;
  store-down-down)
    "${COMPOSE[@]}" --profile store-down rm -s -f backend-store-down
    ;;
  metrics)
    for container in $("${COMPOSE[@]}" ps -q backend); do
      echo "# container ${container}"
      docker exec "${container}" wget -q -O - http://127.0.0.1:8081/actuator/prometheus
    done
    ;;
  *)
    echo "usage: $0 up|down|images|store-down-up|store-down-down|metrics" >&2
    exit 2
    ;;
esac
