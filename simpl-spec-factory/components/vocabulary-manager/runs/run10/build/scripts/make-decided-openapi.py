#!/usr/bin/env python3
"""Builds docs/openapi-decided.yaml: the published OpenAPI with every contract change of D79 (and D91, D110, D116)
applied, plus the 401, 403 and 503 responses of D17 and D44. The published file in input/specs/api stays unchanged
(D39). Usage: python3 scripts/make-decided-openapi.py <published.yaml> <decided.yaml>"""
import copy
import sys

import yaml

INT32_MAX = 2147483647


def problem_response(description, example):
    return {
        "description": description,
        "content": {"application/problem+json": {"schema": {"$ref": "#/components/schemas/Problem"}, "example": example}},
    }


def main(source, target):
    with open(source, encoding="utf-8") as handle:
        api = yaml.safe_load(handle)
    api["info"]["version"] = "1.0.0-decided"
    api["info"]["description"] += (
        "\n\nDecided contract of the factory build: the published contract with the changes of decision D79 "
        "(and D91, D110, D116) applied. Generated by scripts/make-decided-openapi.py."
    )
    api["servers"] = [{"url": "http://localhost:8196/v1", "description": "Local stack (build profile)"}]
    components = api["components"]

    # D40: OpenID Connect through the Keycloak realm, no scopes checked.
    components["securitySchemes"] = {
        "OpenIdConnect": {
            "type": "openIdConnect",
            "openIdConnectUrl": "http://localhost:8193/realms/simpl/.well-known/openid-configuration",
            "description": "Bearer token of the Keycloak realm 'simpl' with audience 'vocabulary-manager-be'. "
            "Realm roles GA_VOCABULARY_VIEWER (reads and searches) and GA_VOCABULARY_ADMIN (all operations).",
        }
    }
    api["security"] = [{"OpenIdConnect": []}]

    responses = components["responses"]
    responses["UnauthorizedResponse"] = problem_response(
        "No or invalid bearer token (D17).",
        {"type": "urn:problem-type:simpl:unauthorized", "title": "Unauthorized", "status": 401,
         "detail": "The access token is missing or not valid."},
    )
    responses["ForbiddenResponse"] = problem_response(
        "Valid token without the required role (D16, D17).",
        {"type": "urn:problem-type:simpl:forbidden", "title": "Forbidden", "status": 403,
         "detail": "You are not allowed to perform this operation."},
    )
    responses["ServiceUnavailableResponse"] = problem_response(
        "Store or identity provider not available, or too many uploads (D44, D92, D103).",
        {"type": "urn:problem-type:belgif:serviceUnavailable", "title": "Service Unavailable", "status": 503,
         "detail": "The vocabulary store is not available. Retry later."},
    )
    responses["ServiceUnavailableResponse"]["headers"] = {
        "Retry-After": {"description": "Seconds to wait before retrying.", "schema": {"type": "integer", "example": 5}}
    }
    responses["ExternalVocabularyNotFoundResponse"]["content"]["application/problem+json"]["example"]["issues"] = [
        {"in": "path", "name": "name", "detail": "External vocabulary with name 'DublinCoreTerms' was not found."}
    ]

    for path, item in api["paths"].items():
        for method, operation in item.items():
            secured = operation.get("security") != []
            responses_of = operation["responses"]
            if secured:
                responses_of["401"] = {"$ref": "#/components/responses/UnauthorizedResponse"}
                responses_of["403"] = {"$ref": "#/components/responses/ForbiddenResponse"}
                responses_of["503"] = {"$ref": "#/components/responses/ServiceUnavailableResponse"}
            if path.startswith("/external-vocabularies/{name}") and "404" in responses_of:
                responses_of["404"] = {"$ref": "#/components/responses/ExternalVocabularyNotFoundResponse"}
            body = operation.get("requestBody", {}).get("content", {})
            if "application/json" in body:
                responses_of["413"] = {"$ref": "#/components/responses/UploadTooLargeResponse"}
                responses_of.setdefault("415", {"$ref": "#/components/responses/UnsupportedMediaTypeResponse"})
            if "multipart/form-data" in body:
                responses_of.setdefault("415", {"$ref": "#/components/responses/UnsupportedMediaTypeResponse"})
                body["multipart/form-data"]["encoding"] = {"vocabularyFile": {"contentType": "text/turtle"}}
            if path == "/vocabularies/{vocabularyName}/versions" and method == "post":
                responses_of["409"] = {"$ref": "#/components/responses/ConflictResponse"}
            for parameter in operation.get("parameters", []):
                if parameter.get("name") == "version" and parameter.get("in") == "path":
                    parameter["schema"] = {"type": "integer", "format": "int32", "minimum": 1, "maximum": INT32_MAX}

    parameters = components["parameters"]
    # D19: name filter relaxed.
    parameters["VocabularyNameQuery"]["schema"] = {"type": "string", "minLength": 1, "maxLength": 64,
                                                   "pattern": "^[A-Za-z0-9]+$"}
    parameters["VocabularyNameQuery"]["description"] = "Case-insensitive 'contains' filter on the vocabulary name (D19)."
    # D22, D91: paging limits.
    parameters["PageQuery"]["schema"] = {"type": "integer", "format": "int32", "default": 1, "minimum": 1,
                                         "maximum": INT32_MAX}
    parameters["PageSizeQuery"]["schema"] = {"type": "integer", "format": "int32", "default": 20, "minimum": 1,
                                             "maximum": 100}
    # D116: date formats.
    for name in ("CreationDateQuery", "LastUpdatedQuery"):
        parameters[name]["schema"] = {
            "anyOf": [{"type": "string", "format": "date"}, {"type": "string", "format": "date-time"}]
        }
    schemas = components["schemas"]
    text_1000 = {"type": "string", "minLength": 1, "maxLength": 1000}

    # D37, D52, D7: create and new-version payloads.
    create = schemas["CreateVocabularyPayload"]
    create["additionalProperties"] = False
    create["properties"]["description"].update(text_1000)
    create["properties"]["changelog"].update(text_1000)
    version = schemas["CreateNewVocabularyVersionPayload"]
    version["additionalProperties"] = False
    version["properties"]["description"].update(text_1000)
    version["properties"]["changelog"].update(text_1000)
    # D56, D73: external registration.
    external = schemas["CreateExternalVocabularyPayload"]
    external["additionalProperties"] = False
    external["properties"]["aliasUris"]["maxItems"] = 20
    external["properties"]["aliasUris"]["uniqueItems"] = True
    external["properties"]["description"]["maxLength"] = 1000
    # D38: search limits.
    schemas["VocabularySearchRequest"]["properties"]["items"]["maxItems"] = 100
    schemas["VocabularySearchItemRequest"]["properties"]["version"].update({"format": "int32", "maximum": INT32_MAX})
    search = schemas["ExternalVocabularySearchRequest"]
    for array in ("namespaceUris", "aliasUris"):
        search["properties"][array].update({"minItems": 1, "maxItems": 100})
    schemas["ExternalVocabularyContentRequest"]["additionalProperties"] = False
    schemas["VocabularyStatusPatchRequest"]["additionalProperties"] = False

    # D5, D27, D10, D110: response objects.
    for name in ("VocabularyMetadata", "VocabularyVersionMetadataResponse"):
        properties = schemas[name]["properties"]
        new_properties = {}
        for key, value in properties.items():
            new_properties[key] = value
            if key == "contentHref":
                new_properties["latestVersionHref"] = {"type": "string",
                                                       "example": "/vocabularies/HealthcareVocabulary/versions/3"}
            if key == "status":
                new_properties["createdBy"] = {"type": "string", "example": "johndoe@example.com"}
        schemas[name]["properties"] = new_properties
    schemas["VocabularyVersionMetadataResponse"]["required"] = ["validationWarnings"]
    schemas["VocabularyValidationWarning"]["properties"]["code"]["enum"] = [
        "externalReferenceSkipped", "deprecatedVocabularyReference", "semanticReasoningSkipped"]
    schemas["ExternalVocabulary"]["required"] = ["aliasUris"]
    for name, schema in schemas.items():
        for key, value in schema.get("properties", {}).items():
            if isinstance(value, dict) and value.get("type") == "integer" and "format" not in value:
                value["format"] = "int64" if key == "total" else "int32"

    with open(target, "w", encoding="utf-8") as handle:
        handle.write("# Generated by scripts/make-decided-openapi.py from the published contract; do not edit by hand.\n")
        yaml.safe_dump(api, handle, sort_keys=False, allow_unicode=True, width=120)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
