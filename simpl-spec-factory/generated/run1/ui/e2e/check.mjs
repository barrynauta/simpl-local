import { chromium } from 'playwright-core'
const dir = process.argv[2]
const name = 'Uicheck' + Date.now()
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const errors = []
async function session(user) {
  const ctx = await browser.newContext()
  const page = await ctx.newPage()
  page.on('pageerror', (e) => errors.push(`${user} pageerror: ${e.message}`))
  page.on('console', (m) => { if (m.type() === 'error') errors.push(`${user} console: ${m.text()}`) })
  await page.goto('http://localhost:4333/')
  await page.waitForURL(/localhost:8183/)
  await page.fill('#username', user)
  await page.fill('#password', 'password')
  await page.click('#kc-login')
  await page.waitForURL(/localhost:4333\/$/)
  return { ctx, page }
}
const log = (s) => console.log('OK   ' + s)

// Admin flow
const { page } = await session('ga-admin')
await page.getByTestId('vocabulary-table').waitFor()
log('admin sees the vocabulary list')
await page.getByTestId('new-vocabulary').click()
await page.fill('input[name=name]', name)
await page.fill('textarea[name=description]', 'Created by the UI check')
await page.setInputFiles('input[name=vocabularyFile]', dir + '/bad.ttl')
await page.getByTestId('precheck-errors').waitFor()
log('pre-check shows syntax error on file selection')
await page.setInputFiles('input[name=vocabularyFile]', dir + '/v1.ttl')
await page.getByTestId('precheck-ok').waitFor()
log('pre-check passes for a valid file')
await page.click('button[type=submit]')
await page.getByTestId('vocabulary-name').waitFor()
const notice = await page.locator('.notices').innerText()
if (!notice.includes('version 1')) throw new Error('no confirmation: ' + notice)
log('create confirmation: ' + notice.split('\n')[1])
await page.getByTestId('update-button').click()
await page.getByTestId('new-version-form').waitFor()
await page.waitForFunction(() => (document.querySelector('textarea[name=content]')?.value ?? '').includes('ex:Person'), null, { timeout: 10000 })
const prefilled = await page.locator('textarea[name=content]').inputValue()
if (!prefilled.includes('ex:Person')) throw new Error('content not prefilled')
log('new version form is prefilled')
await page.fill('textarea[name=changelog]', 'Second version from UI')
await page.locator('textarea[name=content]').fill(prefilled + '\nex:Address a owl:Class .\n')
await page.getByTestId('precheck-ok').waitFor()
await page.click('button[type=submit]')
await page.waitForURL(new RegExp(`/vocabularies/${name}$`))
await page.locator('[data-testid=version-history] tr[data-version="1"]').waitFor()
const history = await page.getByTestId('version-history').innerText()
if (!history.includes('Deprecated')) throw new Error('history has no deprecated version')
await page.getByTestId('deprecation-warning').first().waitFor()
log('history shows v1 deprecated with warning: ' + (await page.getByTestId('deprecation-warning').first().innerText()).slice(0, 90))
// Server-side validation report: submit a broken reference
await page.getByTestId('update-button').click()
await page.getByTestId('new-version-form').waitFor()
await page.fill('textarea[name=changelog]', 'Broken reference')
const c = await page.locator('textarea[name=content]').inputValue()
await page.locator('textarea[name=content]').fill(c + '\nex:Home a <https://vocabulary.simpl.local/vocabularies/Ghost/1#Thing> .\n')
await page.getByTestId('precheck-ok').waitFor()
await page.click('button[type=submit]')
await page.getByTestId('validation-report').waitFor()
log('validation report shown: ' + (await page.getByTestId('validation-report').innerText()).split('\n')[1])
// Status change
await page.goto(`http://localhost:4333/vocabularies/${name}`)
await page.getByTestId('status-button').click()
await page.selectOption('[data-testid=status-change] select', 'DEPRECATED')
await page.click('[data-testid=status-change] button:has-text("Apply status")')
await page.locator('.notices :text("successfully updated")').waitFor()
await page.getByTestId('deprecation-warning').first().waitFor()
log('status changed to Deprecated with notification and warning')
await page.goto('http://localhost:4333/')
await page.getByTestId('list-deprecation-warning').waitFor()
log('list shows deprecation warning')

// Viewer: no admin actions
const viewer = await session('ga-viewer')
await viewer.page.getByTestId('vocabulary-table').waitFor()
if (await viewer.page.getByTestId('new-vocabulary').count()) throw new Error('viewer sees New Vocabulary')
await viewer.page.goto(`http://localhost:4333/vocabularies/${name}`)
await viewer.page.getByTestId('vocabulary-name').waitFor()
if (await viewer.page.getByTestId('status-button').count()) throw new Error('viewer sees Change status')
log('viewer sees no create or status actions')

// No role
const norole = await session('ga-norole')
await norole.page.getByTestId('no-role').waitFor()
log('user without role sees access denied')

await browser.close()
console.log(errors.length ? 'BROWSER ERRORS:\n' + errors.join('\n') : 'No browser errors.')
