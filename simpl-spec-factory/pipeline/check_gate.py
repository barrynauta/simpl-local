#!/usr/bin/env python3
"""Step 30b: the gate before the writers start.

Passes when every blocker of steps 20b and 23b is closed by a decision in
<component>/decisions/decisions.json (or marked as an accepted risk), and every
glossary term with status proposed or open in validation/glossary.md appears in
decisions/glossary.md. Lists majors without a default (warning, not a failure).

Writes <component>/decisions/gate.md. Exit code 0 when the gate passes, 1 when not.

Run: python3 pipeline/check_gate.py contract-management
"""
import json
import re
import sys
from pathlib import Path

FACTORY = Path(__file__).resolve().parent.parent


def load(p, default):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else default


def terms(md, statuses):
    out = []
    for r in md.splitlines():
        if not r.startswith("| ") or r.count("|") < 7 or r.startswith("| Term"):
            continue
        last = r.rstrip(" |").rsplit("|", 1)[-1].strip().lower()
        if any(last.startswith(s) for s in statuses):
            out.append(re.sub(r"[`*]", "", r.split("|")[1]).strip())
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    name = sys.argv[1]
    comp = FACTORY / name
    v, d = comp / "validation", comp / "decisions"
    findings = [f | {"src": "20b"} for f in load(v / "ac-findings.json", [])] + \
               [f | {"src": "23b"} for f in load(v / "domain-findings.json", [])]
    decisions = load(d / "decisions.json", [])
    closed = {}
    for dec in decisions:
        for fid in dec.get("closes", []):
            closed.setdefault(fid, []).append(dec)
    # 20b and 23b both number from 1 (F- and D- prefixes), so ids are unique across the two.
    blockers = [f for f in findings if f["severity"] == "blocker"]
    majors = [f for f in findings if f["severity"] == "major"]
    open_blockers = [f for f in blockers if f["id"] not in closed]
    risk = [f for f in blockers if f["id"] in closed and all(x.get("status") == "accepted risk" for x in closed[f["id"]])]
    majors_open = [f for f in majors if f["id"] not in closed]
    draft = (v / "glossary.md").read_text(encoding="utf-8") if (v / "glossary.md").exists() else ""
    final = (d / "glossary.md").read_text(encoding="utf-8") if (d / "glossary.md").exists() else ""
    to_decide = terms(draft, ("proposed", "open"))
    final_low = final.lower()
    undecided = [t for t in to_decide if t.split(",")[0].split("(")[0].strip().lower() not in final_low]
    unknown = sorted({fid for dec in decisions for fid in dec.get("closes", [])} - {f["id"] for f in findings})
    # Consistency warnings: error body formats, and findings closed by more than one decision.
    text = " ".join(json.dumps(x, ensure_ascii=False) for x in decisions)
    formats = [f for f, rx in (("problem+json (RFC 7807/9457)", r"(?i)problem\+json|problem details|problem type|rfc ?(7807|9457)|\bProblem\b"),
                               ("error object with code and message", r"errorCode|errorMessage|\bError body\b|\{\s*\\?\"code\\?\"\s*:"))
               if re.search(rx, text)]
    multi = {fid: [x["id"] for x in decs] for fid, decs in closed.items() if len(decs) > 1}
    passed = not open_blockers and not undecided and bool(decisions)

    md = [f"# Gate (step 30b): {name}", "",
          f"**{'PASSED' if passed else 'NOT PASSED'}.** Generated by [`pipeline/check_gate.py`](../../pipeline/check_gate.py).", "",
          "| Check | Result |", "|---|---|",
          f"| Decisions | {len(decisions)} ({', '.join(f'{k} {v}' for k, v in sorted(__import__('collections').Counter(x.get('status', '?') for x in decisions).items()))}) |",
          f"| Blockers closed | {len(blockers) - len(open_blockers)} of {len(blockers)} ({len(risk)} only as accepted risk) |",
          f"| Majors with a default | {len(majors) - len(majors_open)} of {len(majors)} |",
          f"| Glossary terms decided | {len(to_decide) - len(undecided)} of {len(to_decide)} |",
          f"| Decisions citing unknown finding ids | {len(unknown)} |", ""]
    if open_blockers:
        md += ["## Blockers without a decision", ""] + [f"- {f['id']} ({f['src']}): {f['finding'][:160]}" for f in open_blockers] + [""]
    if undecided:
        md += ["## Glossary terms not in the final glossary", ""] + [f"- {t}" for t in undecided] + [""]
    if risk:
        md += ["## Blockers closed only as accepted risk", ""] + [f"- {f['id']}: {f['finding'][:160]}" for f in risk] + [""]
    if majors_open:
        md += ["## Majors without a default (warning)", ""] + [f"- {f['id']} ({f['src']}): {f['finding'][:160]}" for f in majors_open] + [""]
    if len(formats) > 1:
        md += ["## Warning: more than one error body format", "",
               "The decisions mention " + " and ".join(formats) + ". Check that one format applies to the whole component.", ""]
    if multi:
        md += ["## Warning: findings closed by more than one decision", "",
               "Check that these decisions agree.", ""] + [f"- {fid}: {', '.join(ids)}" for fid, ids in sorted(multi.items())] + [""]
    if unknown:
        md += ["## Unknown ids in `closes`", "", ", ".join(unknown), ""]
    d.mkdir(exist_ok=True)
    (d / "gate.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{name}: gate {'passed' if passed else 'NOT passed'}; blockers open {len(open_blockers)}, "
          f"terms undecided {len(undecided)}, majors without default {len(majors_open)}; "
          f"warnings: error formats {len(formats)}, findings with several decisions {len(multi)}")
    sys.exit(0 if passed else 1)


if __name__ == "__main__":
    main()
